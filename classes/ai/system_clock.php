class system_clock implements clock {
    #[\Override]
    public function time(): int {
        return time();
    }

    #[\Override]
    public function sleep(int $milliseconds): void {
        if ($milliseconds > 0) {
            usleep($milliseconds * 1000);
        }
    }
}
